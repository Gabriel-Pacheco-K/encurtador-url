CREATE TABLE short_urls (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(32)   NOT NULL UNIQUE,
    original_url VARCHAR(2048) NOT NULL,
    manage_token VARCHAR(64)   NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE,
    click_count  BIGINT        NOT NULL DEFAULT 0
);

CREATE TABLE clicks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_url_id BIGINT      NOT NULL REFERENCES short_urls (id) ON DELETE CASCADE,
    clicked_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    clicked_on   DATE        NOT NULL,
    referrer     VARCHAR(255),
    browser      VARCHAR(30) NOT NULL,
    device       VARCHAR(30) NOT NULL
);

-- Cobre a consulta de cliques por dia de um link.
CREATE INDEX idx_clicks_url_day ON clicks (short_url_id, clicked_on);
